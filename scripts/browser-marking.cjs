async (page) => {
  const errors = []
  page.on("pageerror", e => errors.push(e.message))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto("http://127.0.0.1:5173/PhysDrill/")
  await page.evaluate(() => localStorage.removeItem("physdrill.v1"))
  await page.reload()
  await page.screenshot({ path: "docs/assets/overview.png", fullPage: true })
  await page.getByRole("button", { name: "快速训练", exact: true }).click()
  await page.getByRole("combobox", { name: "顺序", exact: true }).selectOption("source")
  await page.getByRole("button", { name: "开始这一轮" }).click()
  await page.getByLabel("你的程序 / 作答").fill("sin[x]")
  await page.reload()
  if (await page.getByLabel("你的程序 / 作答").inputValue() !== "sin[x]") throw Error("Draft lost")
  await page.screenshot({ path: ".local/frame1.png" })
  await page.getByRole("button", { name: "提交并检查" }).click()
  await page.getByText("需要订正或核对写法。", { exact: false }).waitFor()
  if (await page.locator(".reference-answer pre").innerText() !== "Sin[x]") throw Error("Reference mismatch")
  if (await page.locator(".explanation[open], .wolfram-result[open]").count()) throw Error("Details should start collapsed")
  const color = await page.locator(".reference-answer pre").evaluate(e => getComputedStyle(e).color)
  if (color !== "rgb(180, 35, 44)") throw Error("Answer color")
  await page.screenshot({ path: "docs/assets/drill.png", fullPage: true })
  await page.screenshot({ path: ".local/frame2.png" })
  await page.reload()
  await page.getByText("需要订正或核对写法。", { exact: false }).waitFor()
  await page.getByRole("button", { name: "答错了", exact: true }).click()
  await page.getByLabel("你的程序 / 作答").fill("Cos[x]")
  await page.getByRole("button", { name: "提交并检查" }).click()
  await page.getByText("A-002 与参考程序匹配", { exact: false }).waitFor()
  if (await page.getByLabel("你的程序 / 作答").inputValue() !== "") throw Error("Did not advance")
  await page.screenshot({ path: ".local/frame3.png" })
  await page.reload()
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem("physdrill.v1")))
  if (saved.attempts.length !== 2 || saved.session.qid !== "A-003") throw Error("Records not durable")
  await page.getByRole("button", { name: /^错题本/ }).click()
  if (await page.locator(".question-row").count() !== 1) throw Error("Wrong book")
  await page.screenshot({ path: ".local/frame4.png" })
  await page.getByRole("button", { name: "题库模块", exact: true }).click()
  await page.getByPlaceholder("搜索题目、命令或 ID……").fill("C-014")
  await page.locator(".question-title").click()
  await page.getByText("展开 Wolfram 图形与运行结果", { exact: true }).click()
  await page.locator(".wolfram-result img").waitFor()
  await page.waitForFunction(() => Array.from(document.querySelectorAll(".wolfram-result img")).every(i => i.complete && i.naturalWidth > 0))
  await page.screenshot({ path: "docs/assets/wolfram.png", fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error("Mobile graphic overflow")
  await page.screenshot({ path: "docs/assets/mobile-wolfram.png", fullPage: true })
  await page.getByRole("button", { name: "关闭 ×", exact: true }).click()
  await page.getByRole("button", { name: "快速训练", exact: true }).click()
  await page.getByLabel("你的程序 / 作答").fill("tan[x]")
  await page.getByRole("button", { name: "提交并检查" }).click()
  await page.screenshot({ path: "docs/assets/mobile-drill.png", fullPage: true })
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error("Mobile correction overflow")
  if (errors.length) throw Error(errors.join("\n"))
  return { passed: ["correction", "matching auto-pass", "refresh", "wrong book", "answer color", "Wolfram image", "desktop", "mobile"], attempts: saved.attempts.length }
}
